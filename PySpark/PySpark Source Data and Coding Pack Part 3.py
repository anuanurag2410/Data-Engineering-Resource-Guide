# Question 3: Create order history with duplicate events,
# completed updates, cancelled orders and pending orders.

q3_data = [
    ("O101", "Anurag", 1200, "Pending", 1),
    ("O101", "Anurag", 1200, "Completed", 2),

    ("O102", "Stuti", 800, "Pending", 1),
    ("O102", "Stuti", 900, "Completed", 2),
    ("O102", "Stuti", 950, "Completed", 3),

    ("O103", "Shalini", 600, "Completed", 1),

    ("O104", "Akash", 500, "Pending", 1),
    ("O104", "Akash", 500, "Cancelled", 2),

    ("O105", "Ravi", 1500, "Completed", 1),
    ("O105", "Ravi", 1500, "Completed", 1),  # Duplicate

    ("O106", "Stuti", 700, "Completed", 1),
    ("O107", "Anurag", 400, "Pending", 1)
]

q3_columns = [
    "order_id", "customer_name",
    "amount", "status", "event_version"
]

q3_df = spark.createDataFrame(
    q3_data, q3_columns
)

print("REVENUE SOURCE DATA")
q3_df.orderBy(
    "order_id", "event_version"
).show(truncate=False)


# COMMAND ----------

# DBTITLE 1,Step 1 - Remove Exact Duplicate Events
q3_dedup_df=q3_df.dropDuplicates()

# COMMAND ----------

# DBTITLE 1,Step 2 - Select the Latest version of every order
version_window = (
    Window.partitionBy("order_id")
    .orderBy(F.col("event_version").desc())
)

q3_latest_df = (
    q3_dedup_df
    .withColumn(
        "row_num",
        F.row_number().over(version_window)
    )
    .filter(F.col("row_num") == 1)
    .drop("row_num")
)

print("LATEST ORDER STATES")
q3_latest_df.orderBy("order_id").show()

# COMMAND ----------

# DBTITLE 1,Step 3 -keep only completed records
q3_completed_df=q3_latest_df.filter(F.col("status")=="Completed")
print("COMPLETED ORDERS ONLY....")
q3_completed_df.orderBy("order_id").show()

# COMMAND ----------

# DBTITLE 1,Step 4 - Calculcate the Revenue per customer
q3_result = (
    q3_completed_df
    .groupBy("customer_name")
    .agg(
        F.count("*").alias("completed_orders"),
        F.sum("amount").alias("total_revenue")
    )
    .orderBy(F.col("Total_Revenue").desc(),
             F.col("customer_name").asc()
             )
    )

    
print("FINAL CUSTOMER REVENUE")
q3_result.show(truncate=False)

